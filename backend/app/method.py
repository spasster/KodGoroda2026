def _principles(survey, th: dict, below: str) -> list[str]:
    """Общие правила и светофор. Строки про заметки и подтверждения есть, только если правило включено в signals.json."""
    rules = th["status"]
    months = int(th["active_months"])
    out = list(PRINCIPLES)
    out.append("Светофор месяца: «положительная оценка», если находок нет; «зона внимания», если находка одна; "
               "«критичный сигнал», если у находки высокая важность или находок две и больше.")
    if rules.get("notes_neutral"):
        out.append("Заметка (низкая важность) светофор не красит. Её видно в карточке стажёра, решение за HR.")
    if rules.get("one_text_finding"):
        out.append("Стажёр и наставник в одном месяце пишут об одной проблеме: считаем это одной находкой.")
    if rules.get("low_index"):
        out.append(f"Средняя оценка стажёра или наставника ниже {below} считается ещё одной находкой. "
                   "Вместе с сигналом средней важности месяц становится «критичным сигналом».")
    out.append(f"Статус стажёра считаем по ситуациям за последние {months} {plural(months, 'месяц', 'месяца', 'месяцев')}: "
               "«критичный сигнал», если высокая важность держится два месяца или ситуаций две и больше, "
               "«зона внимания», если ситуация одна.")
    return out


def _quality_line(quality: dict | None) -> str:
    """« ИИ нашёл 26 из 31 проблемы в публичных отзывах стажёров и наставников, на анкетах МГТС его не проверяли»."""
    sets = (quality or {}).get("sets") or []
    real = next((x for x in sets if x.get("id") == "holdout"), None)
    if not real:
        return ""
    found, total = real["model"]["found"], real["problems"]
    return (f" ИИ нашёл {found} из {total} {plural(total, 'проблемы', 'проблем', 'проблем')} в публичных отзывах "
            "стажёров и наставников. На анкетах МГТС качество ИИ не проверяли: разметки для них нет.")


def method(snap: Snapshot, quality: dict | None) -> dict:
    survey, th = snap.ds.survey, snap.th

    def points(share: float) -> float:
        return survey.scale_min + share * survey.scale_range

    def pts(group: str, key: str) -> str:
        return num(th[group][key] * survey.scale_range)

    items = _signals(pts, score_str(floor(points(th["low_question"]["max_score"]) + 1e-9)),
                     num(points(th["text_vs_score"]["min_index"])), _paired(survey),
                     bool(th["text_vs_score"].get("confirm")), _quality_line(quality))
    for item in items:
        item["how"] = item["how"].replace("{drop}", str(round(th["silence"]["length_drop"] * 100)))
        mine = [s for s in snap.signals if s.type == item["type"]]
        for status in ("open", "confirmed", "rejected"):
            item[status] = sum(s.review.status == status for s in mine)
    below = num(points(th["baseline"]["index_below"]))
    return {
        "principles": _principles(survey, th, below),
        "signals": items,
        "baseline": ("Сравниваем с тем, как это видно без дашборда: HR смотрит среднюю оценку за один месяц "
                     f"и реагирует, когда она ниже {below}. Порог выбрали мы сами, его нужно уточнить у HR. "
                     "Пороги сигналов подобраны на пяти парах МГТС за шесть месяцев, на большой программе "
                     "их нужно проверить заново."),
        "quality": quality,
    }
