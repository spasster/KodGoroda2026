def _paired(survey) -> str:
    """«Понятность задач» и «Понимание задач и ожиданий», …: вопросы, которые у сторон про одно и то же."""
    pairs = []
    for p in survey.paired:
        a, b = survey.question("intern", p.get("intern", "")), survey.question("mentor", p.get("mentor", ""))
        if a and b:
            pairs.append(f"«{a.name}» и «{b.name}»")
    if not pairs:
        return ""
    n = len(pairs)
    if n == 1:
        return f" Напрямую сравнима только одна пара вопросов: {pairs[0]}."
    return f" Напрямую сравнимы только {n} {plural(n, 'пара', 'пары', 'пар')} вопросов: {'; '.join(pairs)}."


