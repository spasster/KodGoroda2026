def method(snap: Snapshot, quality: dict | None) -> dict:
    survey, th = snap.ds.survey, snap.th

    def points(share: float) -> float:
        return survey.scale_min + share * survey.scale_range

    def pts(group: str, key: str) -> str:
        return num(th[group][key] * survey.scale_range)

    items = _signals(pts, score_str(r1(points(th["low_question"]["max_score"]))),
                     num(points(th["text_vs_score"]["min_index"])))
    for item in items:
        item["how"] = item["how"].replace("{drop}", str(round(th["silence"]["length_drop"] * 100)))
        mine = [s for s in snap.signals if s.type == item["type"]]
        for status in ("open", "confirmed", "rejected"):
            item[status] = sum(s.review.status == status for s in mine)
    return {
        "principles": PRINCIPLES,
        "signals": items,
        "baseline": ("Сравниваем с тем, как это видно без дашборда: HR смотрит среднюю оценку за один месяц "
                     f"и реагирует, когда она ниже {num(points(th['baseline']['index_below']))}."),
        "quality": quality,
    }
