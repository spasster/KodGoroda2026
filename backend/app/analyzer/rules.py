@dataclass(frozen=True)
class Rule:
    topic: str | None  # None: только тональность
    weight: float  # меньше нуля: проблема, больше нуля: хорошее
    pattern: re.Pattern
    flip: bool = False  # «не» перед фразой меняет знак: «не скучно», «не интересно»
    flip_topic: str | None = None  # тема после смены знака; None у хорошего: только тональность
    roles: tuple[str, ...] = ()  # пусто: для обеих ролей


def _r(topic: str | None, weight: float, pattern: str, flip: bool = False, flip_topic: str | None = None,
       roles: tuple[str, ...] = ()) -> Rule:
    return Rule(topic, weight, re.compile(pattern), flip, flip_topic, roles)


