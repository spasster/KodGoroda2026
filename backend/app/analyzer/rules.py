SENTENCE_END = re.compile(r"[.!?…\n]+")
CLAUSE_SEP = re.compile(r";|\s[-–—]\s|,\s*(?=(?:но|а|однако|зато|хотя|только|правда|при\s+этом)\b)|\s(?=(?:но|однако|зато)\s)")
MIN_CLAUSE = 20
BUT_AFTER = re.compile(r"[^.!?…\n]*?\s(?:но|однако)\s")  # дальше в том же предложении есть «но»
LEAD_CONJ = re.compile(r"(?:но|а|однако|зато|хотя|и)\s+", re.IGNORECASE)  # «а своей задачи…» → «своей задачи…»
MIN_QUOTE = 12


def _norm(text: str) -> str:
    """Нижний регистр и е вместо ё без изменения длины: позиции совпадают с исходником."""
    out = []
    for ch in text:
        low = ch.lower()
        if len(low) != 1:
            low = ch
        out.append("е" if low == "ё" else low)
    return "".join(out)


def _negated(norm: str, start: int, end: int) -> bool:
    """Отрицание перед фразой («не нравится») или внутри неё («наставник мало помогает»)."""
    inner = re.findall(r"\w+", norm[start:end])[:-1]
    if any(w in NEGATORS for w in inner):
        return True
    prefix = norm[max(0, start - 50):start]
    cut = max(prefix.rfind(c) for c in ".,;:!?\n()")
    if cut >= 0:
        prefix = prefix[cut + 1:]
    words = re.findall(r"\w+", prefix)
    tail: list[str] = []
    for w in reversed(words):
        if w in CONJUNCTIONS or len(tail) == 3:
            break
        tail.insert(0, w)
    for i, w in enumerate(tail):
        if w in NEGATORS and not (i + 1 < len(tail) and tail[i + 1] == "только"):
            return True
    return False


def _strip_span(text: str, a: int, b: int) -> tuple[int, int]:
    junk = " \t\n\r,;:-–—"
    while a < b and text[a] in junk:
        a += 1
    while b > a and text[b - 1] in junk + ".!?…":
        b -= 1
    return a, b


def quote_span(text: str, start: int, end: int) -> tuple[int, int]:
    """Часть предложения вокруг [start, end): клауза, а если она короткая, всё предложение."""
    s_start = 0
    for m in SENTENCE_END.finditer(text, 0, start):
        s_start = m.end()
    m = SENTENCE_END.search(text, end)
    s_end = m.start() if m else len(text)

    c_start, c_end = s_start, s_end
    for sep in CLAUSE_SEP.finditer(text, s_start, s_end):
        if sep.end() <= start:
            c_start = sep.end()
        elif sep.start() >= end:
            c_end = sep.start()
            break
    a, b = _strip_span(text, c_start, c_end)
    lead = LEAD_CONJ.match(text, a)
    if lead and lead.end() <= start and b - lead.end() >= MIN_CLAUSE:
        a = lead.end()
    if b - a >= MIN_CLAUSE:
        return a, b
    a, b = _strip_span(text, s_start, s_end)
    if b - a >= MIN_QUOTE:
        return a, b
    # Короткое предложение («Устал.») цитируем вместе с соседним.
    prev_start = 0
    for m in SENTENCE_END.finditer(text, 0, max(0, s_start - 1)):
        prev_start = m.end()
    if s_start > 0:
        return _strip_span(text, prev_start, s_end)
    m = SENTENCE_END.search(text, s_end + 1)
    return _strip_span(text, 0, m.start() if m else len(text))


def analyze(text: str, role: str, question_id: str) -> TextInsight:
    norm = _norm(text)
    taken: list[tuple[int, int]] = []
    pos = neg = 0.0
    topics: set[str] = set()
    concerns: list[Concern] = []

    for rule in RULES:
        if rule.roles and role not in rule.roles:
            continue
        for m in rule.pattern.finditer(norm):
            a, b = m.span()
            if a == b or any(a < tb and ta < b for ta, tb in taken):
                continue
            taken.append((a, b))
            weight, topic = rule.weight, rule.topic
            if rule.flip and _negated(norm, a, b):
                weight = -weight
                topic = rule.flip_topic if weight < 0 else ("positive" if topic else None)
            if topic is None:
                pos, neg = (pos + weight, neg) if weight > 0 else (pos, neg - weight)
                continue
            if weight > 0:
                if BUT_AFTER.match(norm, b):
                    weight /= 2  # «помогают, но это не их работа»: после «но» главное
                pos += weight
                topics.add("positive")
                if topic != "positive":
                    topics.add(topic)
                continue
            neg += -weight
            topics.add(topic)
            qa, qb = quote_span(text, a, b)
            if not any(c.label == topic and qa < c.end and c.start < qb for c in concerns):
                concerns.append(Concern(label=topic, quote=text[qa:qb], start=qa, end=qb))

    sentiment = round((pos - neg) / (pos + neg + 1), 2)
    # «Хорошее» только у комментария, который в целом хороший. Жалоба с вежливым
    # «стараюсь» внутри метку «хорошее» не получает: в ручной разметке так не бывает.
    if sentiment <= 0:
        topics.discard("positive")
    concerns.sort(key=lambda c: c.start)
    return TextInsight(sentiment=sentiment, topics=sorted(topics), concerns=concerns, summary=None)
