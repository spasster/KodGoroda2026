def lineup(n: int) -> list[Pair]:
    """Пары набора из n штук: сначала пять из кейса, потом вариации, дальше благополучные без комментариев."""
    pairs = (BASE + EXTRAS)[:n]
    for num in range(len(pairs) + 1, n + 1):
        pairs.append(Pair(
            num, "благополучная, без комментариев", "Контроль: оценки с шумом, комментарии не пишут.", control=True,
            intern_comments=(c(""),) * 5, mentor_comments=(c(""),) * 5,
        ))
    return pairs


def comment_labels() -> dict[str, Comment]:
    """Разметка всех комментариев набора по тексту. Пустой комментарий не размечается."""
    labels: dict[str, Comment] = {}

    def put(cm: Comment):
        if not cm.text:
            return
        assert set(cm.topics) <= TOPICS, cm
        assert cm.quote is None or cm.quote in cm.text, cm
        old = labels.setdefault(cm.text, cm)
        assert old == cm, f"один текст размечен по-разному: {cm.text!r}"

    for p in BASE + EXTRAS:
        for ans in (*p.intern.values(), *p.mentor.values()):
            put(ans.comment)
        for cm in (*p.intern_comments, *p.mentor_comments):
            put(cm)
    for _, _, ans in DEMO:
        put(ans.comment)
    return labels
