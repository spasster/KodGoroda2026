@dataclass(frozen=True)
class Comment:
    text: str
    sentiment: float = 0.0
    topics: tuple[str, ...] = ()
    quote: str | None = None
    sure: bool = True


@dataclass(frozen=True)
class Answer:
    scores: tuple[int, ...]
    comment: Comment


@dataclass
class Pair:
    num: int
    title: str
    story: str
    control: bool = False
    # месяц -> анкета; нет месяца значит, что анкету не заполнили
    intern: dict[int, Answer] = field(default_factory=dict)
    mentor: dict[int, Answer] = field(default_factory=dict)
    # для благополучных вариаций оценки генерирует generate.py, здесь только комментарии по месяцам
    intern_comments: tuple[Comment, ...] = ()
    mentor_comments: tuple[Comment, ...] = ()

    @property
    def pair_id(self) -> str:
        return f"P-{self.num:02d}"

    @property
    def intern_id(self) -> str:
        return f"S-{self.num:02d}"

    @property
    def mentor_id(self) -> str:
        return f"M-{self.num:02d}"

    @property
    def generated(self) -> bool:
        return not self.intern


def a(scores, text="", s=0.0, topics=(), quote=None, sure=True) -> Answer:
    return Answer(tuple(scores), Comment(text, s, tuple(topics), quote, sure))


def c(text, s=0.0, topics=(), quote=None, sure=True) -> Comment:
    return Comment(text, s, tuple(topics), quote, sure)


