"""Сценарии тестового набора.

Пять пар из кейса (P-01…P-05) и пары-вариации, которые generate.py добавляет при --pairs больше 5.

Оценки записаны кортежами в порядке вопросов survey/survey.json:
- стажёр: overall, tasks_interest, tasks_clarity, mentor_support, load;
- наставник: overall, speed, independence, engagement.

Каждый комментарий размечен вручную: тональность от -1 до 1, темы из контракта и дословная цитата,
на которой держится вывод. Разметку читает data/expected.py, чтобы посчитать сигналы по тексту.
sure=False значит, что разметка спорная и анализатор может решить иначе.
"""

